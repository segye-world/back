-- 베이스라인 스키마 (이슈 #16)
--
-- Flyway 도입 시점의 엔티티와 같은 스키마입니다. ddl-auto: create 가 만든 스키마를 기준으로
-- 옮기되, Hibernate 가 무작위로 붙이던 FK 이름만 읽을 수 있는 이름으로 바꿨습니다.
-- 이전 수동 스크립트(db/manual/001, 002)의 결과(source_category_id, schedule_id FK)도 이미 반영돼 있습니다.
--
-- 이 파일은 적용된 뒤에는 수정하지 않습니다. 스키마를 바꿀 때는 V2__... 처럼 새 파일을 추가합니다.

CREATE TABLE member (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email    VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL, -- BCrypt hash
    CONSTRAINT idx_member_email UNIQUE (email)
);

-- 카테고리는 아직 회원 구분 없이 전역입니다(#17 에서 회원별로 분리 예정).
CREATE TABLE category (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    type VARCHAR(10) NOT NULL,
    CONSTRAINT category_type_check CHECK (type IN ('INCOME', 'EXPENSE'))
);

CREATE TABLE schedule (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT       NOT NULL,
    title      VARCHAR(100) NOT NULL,
    date       DATE         NOT NULL,
    start_hour INTEGER      NOT NULL,
    end_hour   INTEGER      NOT NULL,
    color_hex  VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_schedule_member FOREIGN KEY (member_id) REFERENCES member (id)
);
CREATE INDEX idx_schedule_member_date ON schedule (member_id, date);

CREATE TABLE todo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   BIGINT       NOT NULL,
    schedule_id BIGINT,
    label       VARCHAR(200) NOT NULL,
    is_done     BOOLEAN      NOT NULL,
    date        DATE         NOT NULL,
    CONSTRAINT fk_todo_member FOREIGN KEY (member_id) REFERENCES member (id),
    -- 엔티티의 @OnDelete(SET_NULL) 과 같게, 일정이 삭제되면 연결만 끊는다.
    CONSTRAINT fk_todo_schedule FOREIGN KEY (schedule_id) REFERENCES schedule (id) ON DELETE SET NULL
);
CREATE INDEX idx_todo_member_date ON todo (member_id, date);

CREATE TABLE account_record (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id          BIGINT       NOT NULL,
    category_id        BIGINT       NOT NULL,
    -- 지출이 빠져나간 수입원(=지출 수단). 수입 기록에는 없을 수 있다.
    source_category_id BIGINT,
    amount             BIGINT       NOT NULL,
    transaction_time   TIMESTAMP(6) NOT NULL,
    schedule_id        BIGINT,
    memo               VARCHAR(500),
    CONSTRAINT fk_account_record_member FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT fk_account_record_category FOREIGN KEY (category_id) REFERENCES category (id),
    -- 수입원이나 일정이 삭제되어도 기록은 남긴다(엔티티의 @OnDelete(SET_NULL)).
    CONSTRAINT fk_account_record_source_category
        FOREIGN KEY (source_category_id) REFERENCES category (id) ON DELETE SET NULL,
    CONSTRAINT fk_account_record_schedule
        FOREIGN KEY (schedule_id) REFERENCES schedule (id) ON DELETE SET NULL
);
CREATE INDEX idx_ar_member_time ON account_record (member_id, transaction_time);

-- 회원별로 한 달에 하나의 한도만 둔다.
CREATE TABLE budget (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    BIGINT  NOT NULL,
    year         INTEGER NOT NULL,
    month        INTEGER NOT NULL,
    limit_amount BIGINT  NOT NULL,
    CONSTRAINT fk_budget_member FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT idx_budget_member_year_month UNIQUE (member_id, year, month)
);
